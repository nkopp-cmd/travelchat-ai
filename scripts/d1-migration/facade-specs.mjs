// Supabase exit step 3: facade column specs for the Supabase-only tables (migration 0034), generated from the pinned
// catalog so the D1 facade, the D1 DDL and the import read one source. Policies stay hand-written in d1-postgrest.ts.
//   node scripts/d1-migration/facade-specs.mjs > lib/app-data/d1-generated-specs.ts
// Inputs: the 0034 catalog and the 0038 catalog (tables first mapped to preview candidates).
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const KIND = { uuid: "text", text: "text", bpchar: "text", varchar: "text", date: "text", timestamptz: "text",
  int2: "int", int4: "int", int8: "int", float8: "real", numeric: "real", bool: "bool", jsonb: "json", _text: "textArray" };

export const CATALOGS = ["scripts/d1-migration/fixtures/supabase-exit-schema-20261024.json", "scripts/d1-migration/fixtures/supabase-exit-schema-20261024b.json"];

export function mergedCatalog(files = CATALOGS) {
  const parts = files.map(f => JSON.parse(readFileSync(f, "utf8")));
  return { columns: parts.flatMap(p => p.columns), constraints: parts.flatMap(p => p.constraints), indexes: parts.flatMap(p => p.indexes) };
}

export function generateSpecs(schema) {
  const tables = [...new Set(schema.columns.map(c => c.t))].sort();
  const lines = [
    "// Generated by scripts/d1-migration/facade-specs.mjs from scripts/d1-migration/fixtures/supabase-exit-schema-20261024{,b}.json.",
    "// Do not edit: regenerate. Geography/geometry columns are \"unsupported\": the facade refuses to read or write them.",
    "export type GeneratedKind = \"text\" | \"int\" | \"real\" | \"bool\" | \"json\" | \"textArray\" | \"unsupported\";",
    "export type GeneratedDefault = \"uuid\" | \"now\";",
    "export const GENERATED_SPECS: Record<string, { primaryKey: string[]; columns: Record<string, { kind: GeneratedKind; default?: GeneratedDefault }> }> = {",
  ];
  for (const t of tables) {
    const pk = schema.constraints.find(c => c.t === t && c.k === "p");
    if (!pk) throw new Error(`No primary key on ${t}`);
    const keys = pk.def.match(/^PRIMARY KEY \((.+)\)$/)[1].split(", ");
    lines.push(`  ${t}: {`, `    primaryKey: ${JSON.stringify(keys)},`, "    columns: {");
    for (const c of schema.columns.filter(c => c.t === t)) {
      const kind = c.udt === "geography" || c.udt === "geometry" ? "unsupported" : KIND[c.udt];
      if (!kind) throw new Error(`Unsupported type ${c.udt} on ${t}.${c.col}`);
      const def = c.def === "gen_random_uuid()" ? "uuid" : c.def === "now()" ? "now" : null;
      lines.push(`      ${c.col}: { kind: "${kind}"${def ? `, default: "${def}"` : ""} },`);
    }
    lines.push("    },", "  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.stdout.write(generateSpecs(mergedCatalog()));
}
